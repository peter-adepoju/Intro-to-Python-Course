def build():
    """Number every week and day across the whole course."""
    weeks = []
    n = 0
    for phase in PHASES:
        for title, days in phase["weeks"]:
            n += 1
            w = {"week": n, "phase": phase["id"], "title": title, "rest": days is None, "days": []}
            for i, d in enumerate(days or [], 1):
                w["days"].append({"day": i, "id": f"w{n:03d}d{i}", "title": d,
                                  "forge": d.endswith(FORGE) or d == FORGE})
            weeks.append(w)
    phases = [{k: p[k] for k in ("id", "title", "summary")} for p in PHASES]
    return {"phases": phases, "weeks": weeks}


if __name__ == "__main__":
    c = build()
    days = sum(len(w["days"]) for w in c["weeks"])
    print(len(c["weeks"]), "weeks;", days, "lesson days;",
          sum(w["rest"] for w in c["weeks"]), "rest weeks;", round(days * 3), "hours")
